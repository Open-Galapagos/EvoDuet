"""Run an unmodified SimpleTES evaluator from SkyDiscover the way SimpleTES itself runs it.

SimpleTES never imports a task's ``evaluator.py`` into its own process.  Its
``EvaluatorWorker`` (``simpletes/evaluator.py`` upstream) spawns one fresh
interpreter per candidate with

* the candidate written as ``program.py`` into a throw-away directory that is also
  the process's cwd and ``TMPDIR``/``TMP``/``TEMP``,
* ``PYTHONPATH`` = the SimpleTES repo root, so ``simpletes.construction`` imports
  and the repo's ``sitecustomize.py`` runs in every interpreter the evaluator spawns
  (that is what defines the ``GLOBAL_BEST_CONSTRUCTION`` builtin evolved programs read),
* ``SIMPLETES_CAPTURE_CONSTRUCTION_PATH`` / ``SIMPLETES_SHARED_CONSTRUCTION_MAX_BYTES`` set,
* the evaluator loaded from its file path as module ``user_evaluator`` and its
  ``evaluate(path)`` result printed as one JSON line,
* a hard timeout that kills the whole process group, and the SimpleTES error
  conventions (``{"error": ..., "combined_score": -inf}``) on timeout / crash.

``benchmarks/simpletes/`` mirrors the SimpleTES repo root for exactly this purpose
(``simpletes/`` package subset, ``sitecustomize.py``, ``datasets/<family>/<task>/``),
and this module is a synchronous re-implementation of that worker: the runner
script, the environment, the temp-dir handling and the output parsing are copied
from upstream, so SkyDiscover's plain ``Evaluator`` observes the same behaviour
per call as SimpleTES's engine — process isolation, per-call re-import of the
evaluator (module-level constants re-read from the environment), no shared state
between concurrent evaluations, and a bounded wall clock even when the evaluator's
own timeout logic cannot interrupt the candidate.

Each plain task's ``skydiscover_evaluator.py`` (generated by
``scripts/port_simpletes.py``) is a three-statement stub that calls ``make_evaluate``.
"""
from __future__ import annotations

import atexit
import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import textwrap
import uuid
from pathlib import Path
from typing import Any, Callable

SUITE_ROOT = Path(__file__).resolve().parent
if str(SUITE_ROOT) not in sys.path:
    sys.path.insert(0, str(SUITE_ROOT))

from simpletes.construction import (  # noqa: E402  (vendored, byte-identical to upstream)
    CAPTURE_CONSTRUCTION_ENV,
    MAX_SNAPSHOT_BYTES_ENV,
    SHARED_CONSTRUCTION_ENV,
    max_snapshot_bytes,
)
from simpletes.utils.text import DEFAULT_METRICS_ERROR_MAX_CHARS, truncate_error_in_metrics  # noqa: E402

TEMP_EVAL_DIR = tempfile.gettempdir()

# Verbatim copy of simpletes/evaluator.py::_EVAL_RUNNER (SimpleTES @ manifest commit), whitespace included.
EVAL_RUNNER = textwrap.dedent(r'''
import importlib.util
import json
import sys
import traceback

def main():
    if len(sys.argv) != 3:
        print(json.dumps({"error": "Invalid arguments", "combined_score": float("-inf")}))
        sys.exit(1)
    
    evaluator_path = sys.argv[1]
    target_file = sys.argv[2]
    
    try:
        # Load evaluator module
        spec = importlib.util.spec_from_file_location("user_evaluator", evaluator_path)
        if spec is None or spec.loader is None:
            print(json.dumps({"error": f"Could not load evaluator: {evaluator_path}", "combined_score": float("-inf")}))
            sys.exit(1)
        
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod
        spec.loader.exec_module(mod)
        
        # Run evaluation
        result = mod.evaluate(target_file)
        
        # Output result as JSON
        print(json.dumps(result))
        
    except Exception as e:
        error_msg = f"{type(e).__name__}: {e}\n{traceback.format_exc()}"
        print(json.dumps({"error": error_msg, "combined_score": float("-inf")}))
        sys.exit(1)

if __name__ == "__main__":
    main()
''').strip()


def subprocess_env(capture_path: str, shared_construction_path: str | None = None) -> dict[str, str]:
    """EvaluatorWorker._subprocess_env with REPO_ROOT = this suite root."""
    env = os.environ.copy()
    env[CAPTURE_CONSTRUCTION_ENV] = capture_path
    env[MAX_SNAPSHOT_BYTES_ENV] = str(max_snapshot_bytes())
    if shared_construction_path:
        env[SHARED_CONSTRUCTION_ENV] = shared_construction_path
    else:
        env.pop(SHARED_CONSTRUCTION_ENV, None)
    current_pythonpath = env.get("PYTHONPATH")
    env["PYTHONPATH"] = (
        f"{SUITE_ROOT}{os.pathsep}{current_pythonpath}" if current_pythonpath else str(SUITE_ROOT)
    )
    return env


def parse_json_from_output(stdout_text: str) -> dict[str, Any]:
    """EvaluatorWorker._parse_json_from_output: last stdout line that is a JSON object."""
    if not stdout_text or not stdout_text.strip():
        metrics = {"error": "Empty evaluator output", "combined_score": -float("inf")}
        truncate_error_in_metrics(metrics, max_chars=DEFAULT_METRICS_ERROR_MAX_CHARS)
        return metrics
    try:
        for line in reversed(stdout_text.split("\n")):
            line = line.strip()
            if line.startswith("{") and line.endswith("}"):
                try:
                    return json.loads(line)
                except json.JSONDecodeError:
                    continue
        return json.loads(stdout_text)
    except json.JSONDecodeError as e:
        metrics = {"error": f"Invalid JSON output: {e}", "combined_score": -float("inf")}
        truncate_error_in_metrics(metrics, max_chars=DEFAULT_METRICS_ERROR_MAX_CHARS)
        return metrics


def _kill_process_group(proc: subprocess.Popen) -> None:
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    except OSError:
        try:
            proc.kill()
        except ProcessLookupError:
            pass


# Evaluations in flight.  SimpleTES kills the process group on asyncio cancellation;
# SkyDiscover's evaluator thread has no cancellation path, so reap them when the
# SkyDiscover process exits (Ctrl-C included) instead of leaving them to run out
# their timeout.  Note that, as upstream, a candidate the evaluator itself started
# with start_new_session=True is outside that group and is reaped by the
# evaluator's own timeout logic.
_LIVE: set[subprocess.Popen] = set()


def _kill_live_evaluations() -> None:
    for proc in list(_LIVE):
        if proc.poll() is None:
            _kill_process_group(proc)


atexit.register(_kill_live_evaluations)


def run_evaluator(
    evaluator_path: str | os.PathLike,
    code: str,
    *,
    timeout: float,
    python_executable: str | None = None,
    target_filename: str = "program.py",
    shared_construction_path: str | None = None,
) -> dict[str, Any]:
    """Evaluate *code* with the evaluator at *evaluator_path*; returns its metrics dict."""
    evaluator_path = os.path.abspath(os.fspath(evaluator_path))
    eval_dir = os.path.join(TEMP_EVAL_DIR, f"eval_skydiscover_{uuid.uuid4().hex}")
    os.makedirs(eval_dir, exist_ok=True)
    filename = os.path.join(eval_dir, target_filename)
    capture_path = os.path.join(eval_dir, "captured_construction.json")
    env = subprocess_env(capture_path, shared_construction_path)
    try:
        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)
        env["TMPDIR"] = eval_dir
        env["TMP"] = eval_dir
        env["TEMP"] = eval_dir
        proc = subprocess.Popen(
            [python_executable or sys.executable, "-c", EVAL_RUNNER, evaluator_path, filename],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            cwd=eval_dir,
            env=env,
            start_new_session=True,
        )
        _LIVE.add(proc)
        try:
            stdout, stderr = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            _kill_process_group(proc)
            proc.wait()
            metrics = {"error": "timeout", "combined_score": -float("inf")}
            truncate_error_in_metrics(metrics, max_chars=DEFAULT_METRICS_ERROR_MAX_CHARS)
            return metrics
        except BaseException:
            # EvaluatorWorker kills the group on asyncio.CancelledError; the same
            # for KeyboardInterrupt / anything that unwinds this thread.
            _kill_process_group(proc)
            proc.wait()
            raise
        finally:
            _LIVE.discard(proc)
        stdout_text = stdout.decode("utf-8", errors="replace").strip()
        stderr_text = stderr.decode("utf-8", errors="replace").strip()
        if proc.returncode != 0:
            error_msg = stderr_text or stdout_text or f"Process exited with code {proc.returncode}"
            metrics = {"error": error_msg, "combined_score": -float("inf")}
            truncate_error_in_metrics(metrics, max_chars=DEFAULT_METRICS_ERROR_MAX_CHARS)
            return metrics
        metrics = parse_json_from_output(stdout_text)
        truncate_error_in_metrics(metrics, max_chars=DEFAULT_METRICS_ERROR_MAX_CHARS)
        return metrics
    finally:
        shutil.rmtree(eval_dir, ignore_errors=True)


def make_evaluate(
    evaluator_path: str | os.PathLike,
    *,
    timeout: float,
    target_filename: str = "program.py",
    python_executable: str | None = None,
) -> Callable[[str], dict[str, Any]]:
    """Build the ``evaluate(program_path)`` SkyDiscover calls for one task.

    ``timeout`` plays the role of SimpleTES's ``--eval-timeout`` (hard kill).
    ``SIMPLETES_EVAL_PYTHON`` may name the interpreter for the evaluator subprocess
    (SimpleTES's ``--eval-venv``); default is the running one.
    ``SIMPLETES_SHARED_CONSTRUCTION_PATH`` in the environment is forwarded, which is
    how SimpleTES hands a warm-start construction to candidates.
    """
    evaluator_path = os.path.abspath(os.fspath(evaluator_path))

    def evaluate(program_path: str) -> dict[str, Any]:
        with open(program_path, encoding="utf-8") as f:
            code = f.read()
        interpreter = python_executable or os.environ.get("SIMPLETES_EVAL_PYTHON") or None
        return run_evaluator(
            evaluator_path,
            code,
            timeout=timeout,
            python_executable=os.path.abspath(interpreter) if interpreter else None,
            target_filename=target_filename,
            shared_construction_path=os.environ.get(SHARED_CONSTRUCTION_ENV) or None,
        )

    evaluate.__doc__ = f"SimpleTES-style subprocess evaluation with {os.path.basename(os.path.dirname(evaluator_path))}/evaluator.py"
    return evaluate

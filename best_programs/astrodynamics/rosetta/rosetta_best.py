def _optimize_tour():
    """Run seeded evolution followed by full and reduced normalized polishing."""
    seeds, bounds = _seeds_and_bounds()

    lower = np.asarray([lo for lo, _ in bounds], dtype=float)
    upper = np.asarray([hi for _, hi in bounds], dtype=float)
    span = upper - lower
    dimension = len(bounds)

    started = time.monotonic()
    timeout = float(problem.get("timeout_seconds", 300.0))
    global_deadline = started + max(
        70.0, min(175.0, timeout - 80.0)
    )
    final_deadline = started + max(
        100.0, min(270.0, timeout - 12.0)
    )

    best_value = np.inf
    best_x = seeds[0].copy()
    archive = []

    def save(value, x):
        """Store the global winner and several geometrically distinct elites."""
        nonlocal best_value, best_x

        if not np.isfinite(value):
            return

        x = np.asarray(x, dtype=float).copy()
        y = (x - lower) / span

        if value < best_value:
            best_value = float(value)
            best_x = x.copy()

        for index, (old_value, old_x) in enumerate(archive):
            old_y = (old_x - lower) / span
            if np.linalg.norm(y - old_y) < 0.012:
                if value < old_value:
                    archive[index] = (float(value), x)
                    archive.sort(key=lambda item: item[0])
                return

        archive.append((float(value), x))
        archive.sort(key=lambda item: item[0])
        del archive[14:]

    def objective(x):
        """Evaluate one physical chromosome and update the elite archive."""
        value, _ = _tour(x, make_nodes=False)
        if np.isfinite(value):
            save(value, x)
            return float(value)
        return 1.0e6

    for seed in seeds:
        objective(seed)

    rng = np.random.default_rng(SEED)
    population_size = 25 * dimension
    population = np.empty((population_size, dimension), dtype=float)

    copied = min(len(seeds), population_size)
    for row in range(copied):
        population[row] = seeds[row]

    scales = np.array(
        [0.025] * 5
        + [0.045] * 3
        + [0.055] * 5
        + [0.060] * 4
        + [0.080] * 4,
        dtype=float,
    )

    for row in range(copied, population_size):
        if row < int(0.96 * population_size):
            if row % 3:
                source = row % min(5, len(seeds))
            else:
                source = row % len(seeds)

            candidate = seeds[source].copy()
            candidate += rng.normal(0.0, scales * span)
            population[row] = np.clip(candidate, lower, upper)
        else:
            population[row] = rng.uniform(lower, upper)

    def stop_global(xk, convergence):
        """Stop evolution in time to preserve a deterministic polish budget."""
        return time.monotonic() >= global_deadline

    de_result = None
    try:
        de_result = differential_evolution(
            objective,
            bounds,
            init=population,
            seed=SEED,
            maxiter=1200,
            popsize=25,
            tol=1.0e-10,
            atol=1.0e-12,
            mutation=(0.30, 1.10),
            recombination=0.94,
            polish=False,
            updating="immediate",
            workers=1,
            callback=stop_global,
        )
        objective(de_result.x)
    except Exception:
        pass

    unit_bounds = [(0.0, 1.0)] * dimension

    def normalized_objective(y):
        """Evaluate the tour after mapping unit coordinates to physical bounds."""
        y = np.clip(np.asarray(y, dtype=float), 0.0, 1.0)
        return objective(lower + span * y)

    starts = [best_x.copy()]
    if de_result is not None:
        starts.append(np.asarray(de_result.x, dtype=float))
    starts.extend(x for _, x in archive[:5])
    starts.extend(seeds[:3])

    unique = []
    for candidate in starts:
        y = (candidate - lower) / span
        if all(
            np.linalg.norm(y - (old - lower) / span) > 1.0e-6
            for old in unique
        ):
            unique.append(candidate)

    for candidate in unique[:4]:
        if time.monotonic() >= final_deadline - 25.0:
            break

        try:
            y0 = np.clip((candidate - lower) / span, 0.0, 1.0)
            result = minimize(
                normalized_objective,
                y0,
                method="Powell",
                bounds=unit_bounds,
                options={
                    "maxiter": 800,
                    "maxfev": 10500,
                    "xtol": 5.0e-9,
                    "ftol": 2.0e-13,
                },
            )
            normalized_objective(result.x)
        except Exception:
            pass

    # Timing, departure velocity, the Mars/final-Earth turns, and the terminal
    # DSM dominate the residual cost in the demonstrated optimum.
    active = np.array([
        0, 1, 2, 3, 4,
        5, 6, 7,
        9, 10, 12,
        14, 16,
        17, 18, 19, 20,
    ], dtype=int)

    if time.monotonic() < final_deadline - 8.0:
        ybase = np.clip((best_x - lower) / span, 0.0, 1.0)

        def reduced_objective(z):
            """Polish the coordinates controlling the nonzero trajectory burns."""
            y = ybase.copy()
            y[active] = np.clip(np.asarray(z, dtype=float), 0.0, 1.0)
            return normalized_objective(y)

        try:
            result = minimize(
                reduced_objective,
                ybase[active],
                method="Powell",
                bounds=[(0.0, 1.0)] * len(active),
                options={
                    "maxiter": 500,
                    "maxfev": 6000,
                    "xtol": 2.0e-9,
                    "ftol": 8.0e-14,
                },
            )
            reduced_objective(result.x)
        except Exception:
            pass

    value, nodes = _tour(best_x, make_nodes=True)
    if nodes is None or not np.isfinite(value):
        return np.inf, None
    if not _verify_nodes(nodes):
        return np.inf, None

    return float(value), nodes


def _direct_fallback():
    """Construct a valid direct multi-revolution Earth-to-67P fallback."""
    start_lo, start_hi = _window(problem["start"])
    final_epoch = 0.5 * sum(_window(problem["end"]))
    final_r, final_v = _state(problem["end"], final_epoch)

    best_cost = np.inf
    best_nodes = None

    for launch in np.linspace(start_lo, start_hi, 17):
        initial_r, initial_v = _state(problem["start"], launch)

        for departure, arrival in _lambert_options(
            initial_r,
            final_r,
            final_epoch - launch,
            max_revolutions=4,
        ):
            cost = (
                _boundary_cost(
                    departure, initial_v, problem["start"]
                )
                + _boundary_cost(
                    arrival, final_v, problem["end"]
                )
            )

            if cost < best_cost:
                best_cost = float(cost)
                best_nodes = [
                    {
                        "type": "start",
                        "time": float(launch),
                        "planet_id": str(
                            problem["start"].get("planet_id", "0")
                        ),
                        "r": initial_r,
                        "v_before": initial_v,
                        "v_after": departure,
                    },
                    {
                        "type": "end",
                        "time": float(final_epoch),
                        "planet_id": str(
                            problem["end"].get("planet_id", "0")
                        ),
                        "r": final_r,
                        "v_before": arrival,
                        "v_after": final_v,
                    },
                ]

    return float(best_cost), best_nodes


def _format(nodes):
    """Convert NumPy-backed trajectory nodes to the required plain schema."""
    return [
        {
            "type": str(node["type"]),
            "time": float(node["time"]),
            "planet_id": str(node["planet_id"]),
            "r": np.asarray(node["r"], dtype=float).tolist(),
            "v_before": np.asarray(
                node["v_before"], dtype=float
            ).tolist(),
            "v_after": np.asarray(
                node["v_after"], dtype=float
            ).tolist(),
        }
        for node in nodes
    ]


def run_code():
    """Return the best valid direct or E-E-M-E-E-67P trajectory found."""
    try:
        record.event("focused_cartesian_rosetta_mga_search")
    except Exception:
        pass

    fallback_cost, fallback_nodes = _direct_fallback()
    best_cost = fallback_cost
    best_nodes = fallback_nodes
    best_sequence = "direct-multirevolution-Lambert"

    allowed = set(map(str, problem.get("allowed_GA_planets", [])))
    compatible = (
        {"3", "4"}.issubset(allowed)
        and int(problem.get("max_GA", 0)) >= 4
        and int(problem.get("max_DSM", 0)) >= 5
        and int(problem.get("max_nodes", 0)) >= 11
    )

    if compatible:
        try:
            tour_cost, tour_nodes = _optimize_tour()
            if (
                tour_nodes is not None
                and np.isfinite(tour_cost)
                and tour_cost < best_cost
            ):
                best_cost = float(tour_cost)
                best_nodes = tour_nodes
                best_sequence = "E-E-M-E-E-67P"
        except Exception:
            pass

    if best_nodes is None:
        raise RuntimeError("No valid Rosetta trajectory was constructed")

    try:
        record.set("best_sequence", best_sequence)
        record.set("final_cost", float(best_cost))
        record.set("final_nodes", len(best_nodes))
    except Exception:
        pass

    return _format(best_nodes)


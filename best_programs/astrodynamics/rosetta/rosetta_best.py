def _window(spec):
    """Return the inclusive MJD interval represented by a boundary time."""
    t = spec["time"]
    if t["kind"] == "window":
        return float(t["lo"]), float(t["hi"])
    value = float(t.get("value", t.get("mjd")))
    return value, value


def _state(spec, epoch):
    """Return a fixed boundary state or a DE430 planetary state."""
    pid = str(spec.get("planet_id", "0"))
    if pid == "0":
        return (
            np.asarray(spec["state_r"], dtype=float),
            np.asarray(spec["state_v"], dtype=float),
        )
    r, v = tools.ephem(pid, float(epoch))
    return np.asarray(r, dtype=float), np.asarray(v, dtype=float)


def _planet(pid, epoch):
    """Return a planet's heliocentric DE430 state as NumPy arrays."""
    r, v = tools.ephem(str(pid), float(epoch))
    return np.asarray(r, dtype=float), np.asarray(v, dtype=float)


def _piecewise(value, points):
    """Evaluate a clamped piecewise-linear boundary cost curve."""
    points = sorted((float(x), float(y)) for x, y in points)

    if value <= points[0][0]:
        return points[0][1]
    if value >= points[-1][0]:
        return points[-1][1]

    for (x0, y0), (x1, y1) in zip(points[:-1], points[1:]):
        if value <= x1:
            q = (value - x0) / (x1 - x0)
            return y0 + q * (y1 - y0)

    return points[-1][1]


def _boundary_cost(spacecraft_velocity, reference_velocity, spec):
    """Evaluate the configured launcher, capture, or periapsis burn model."""
    vinf = float(np.linalg.norm(
        np.asarray(spacecraft_velocity, dtype=float)
        - np.asarray(reference_velocity, dtype=float)
    ))

    if spec["type"] == "piecewise_linear":
        return float(_piecewise(vinf, spec["breakpoints"]))

    pid = str(spec["planet_id"])
    planet_mu = float(problem["planet_mu"][pid])
    radius = float(problem["planet_radius"][pid])
    periapsis = radius * (1.0 + float(spec["h_factor"]))
    period = float(spec["T_days"]) * DAY

    escape_term = 2.0 * planet_mu / periapsis
    orbit_term = (
        4.0 * np.pi * np.pi * planet_mu * planet_mu
        / (period * period)
    ) ** (1.0 / 3.0)

    return float(
        np.sqrt(vinf * vinf + escape_term)
        - np.sqrt(max(0.0, escape_term - orbit_term))
    )


def _minimum_rp(pid):
    """Return the minimum legal flyby periapsis radius in kilometres."""
    pid = str(pid)
    altitude = float(
        problem.get("flyby", {})
        .get("min_altitude_km", {})
        .get(pid, 200.0)
    )
    return float(problem["planet_radius"][pid]) + altitude


def _lambert_options(r0, r1, tof_days, max_revolutions=0):
    """Enumerate distinct finite prograde Lambert branches for one transfer."""
    if tof_days <= 1.0:
        return []

    answers = []
    for revolutions in range(int(max_revolutions) + 1):
        for lowpath in (True, False):
            try:
                departure, arrival = tools.lambert(
                    np.asarray(r0, dtype=float),
                    np.asarray(r1, dtype=float),
                    float(tof_days) * DAY,
                    MU,
                    prograde=True,
                    lowpath=lowpath,
                    M=revolutions,
                )
                departure = np.asarray(departure, dtype=float)
                arrival = np.asarray(arrival, dtype=float)

                if not (
                    np.all(np.isfinite(departure))
                    and np.all(np.isfinite(arrival))
                ):
                    continue

                duplicate = any(
                    np.linalg.norm(departure - old_departure) < 1.0e-8
                    and np.linalg.norm(arrival - old_arrival) < 1.0e-8
                    for old_departure, old_arrival in answers
                )
                if not duplicate:
                    answers.append((departure, arrival))
            except Exception:
                pass

    return answers


def _local_vinf(epoch, speed, u, v, flip_normal=False):
    """Map normalized direction values into Earth's local orbital frame."""
    r, planet_velocity = _planet("3", epoch)

    tangent = planet_velocity / np.linalg.norm(planet_velocity)
    normal = np.cross(r, planet_velocity)
    normal /= np.linalg.norm(normal)
    transverse = np.cross(normal, tangent)
    transverse /= np.linalg.norm(transverse)

    longitude = 2.0 * np.pi * float(u)
    sin_latitude = 1.0 - 2.0 * float(v)
    if flip_normal:
        sin_latitude = -sin_latitude

    cos_latitude = np.sqrt(max(
        0.0, 1.0 - sin_latitude * sin_latitude
    ))

    direction = (
        np.cos(longitude) * cos_latitude * tangent
        + np.sin(longitude) * cos_latitude * transverse
        + sin_latitude * normal
    )
    return float(speed) * direction


def _inertial_vinf(speed, u, v, flip_z=False):
    """Map normalized spherical values into inertial Cartesian coordinates."""
    longitude = 2.0 * np.pi * float(u)
    z = 2.0 * float(v) - 1.0
    if flip_z:
        z = -z

    radial = np.sqrt(max(0.0, 1.0 - z * z))
    return float(speed) * np.array([
        radial * np.cos(longitude),
        radial * np.sin(longitude),
        z,
    ])


def _angular_vinf(speed, azimuth, elevation):
    """Interpret two direction values as inertial azimuth and elevation."""
    return float(speed) * np.array([
        np.cos(elevation) * np.cos(azimuth),
        np.cos(elevation) * np.sin(azimuth),
        np.sin(elevation),
    ])


def _tour(x, make_nodes=False):
    """Evaluate a Cartesian E-E-M-E-E-67P tour with one DSM per leg."""
    x = np.asarray(x, dtype=float)

    final_epoch = 0.5 * sum(_window(problem["end"]))
    dates = np.asarray(x[0:5], dtype=float)
    initial_vinf = np.asarray(x[5:8], dtype=float)
    fractions = np.asarray(x[8:13], dtype=float)
    rp_factors = np.asarray(x[13:17], dtype=float)
    flyby_angles = np.asarray(x[17:21], dtype=float)

    times = dates.tolist() + [final_epoch]

    minimum_leg_times = (250.0, 500.0, 150.0, 500.0, 500.0)
    for index, minimum in enumerate(minimum_leg_times):
        if times[index + 1] - times[index] < minimum:
            return np.inf, None

    if np.any(fractions <= 0.005) or np.any(fractions >= 0.995):
        return np.inf, None

    try:
        states = [_state(problem["start"], times[0])]
        states.extend(
            _planet(pid, times[index + 1])
            for index, pid in enumerate(SEQUENCE)
        )
        states.append(_state(problem["end"], final_epoch))
    except Exception:
        return np.inf, None

    outgoing = states[0][1] + initial_vinf
    total = _boundary_cost(
        outgoing, states[0][1], problem["start"]
    )

    nodes = []
    if make_nodes:
        nodes.append({
            "type": "start",
            "time": float(times[0]),
            "planet_id": str(problem["start"].get("planet_id", "0")),
            "r": states[0][0],
            "v_before": states[0][1],
            "v_after": outgoing,
        })

    for leg in range(5):
        t0 = float(times[leg])
        t1 = float(times[leg + 1])
        dsm_epoch = t0 + float(fractions[leg]) * (t1 - t0)

        if not t0 < dsm_epoch < t1:
            return np.inf, None

        try:
            dsm_r, velocity_before = tools.propagate_two_body(
                states[leg][0],
                outgoing,
                (dsm_epoch - t0) * DAY,
                MU,
            )
            dsm_r = np.asarray(dsm_r, dtype=float)
            velocity_before = np.asarray(velocity_before, dtype=float)
        except Exception:
            return np.inf, None

        options = _lambert_options(
            dsm_r,
            states[leg + 1][0],
            t1 - dsm_epoch,
            max_revolutions=4 if leg == 4 else 0,
        )
        if not options:
            return np.inf, None

        selected = None
        selected_increment = np.inf

        for velocity_after, arrival_velocity in options:
            dsm_cost = float(np.linalg.norm(
                velocity_after - velocity_before
            ))

            if leg == 4:
                terminal_cost = _boundary_cost(
                    arrival_velocity,
                    states[-1][1],
                    problem["end"],
                )
                increment = dsm_cost + terminal_cost
                candidate = (
                    velocity_after,
                    arrival_velocity,
                    None,
                    terminal_cost,
                )
            else:
                pid = SEQUENCE[leg]
                periapsis = (
                    float(problem["planet_radius"][pid])
                    * float(rp_factors[leg])
                )

                if periapsis < _minimum_rp(pid) * 1.000001:
                    continue

                try:
                    next_outgoing = np.asarray(
                        tools.gravity_assist(
                            arrival_velocity,
                            states[leg + 1][1],
                            float(problem["planet_mu"][pid]),
                            periapsis,
                            float(flyby_angles[leg]),
                        ),
                        dtype=float,
                    )
                except Exception:
                    continue

                if not np.all(np.isfinite(next_outgoing)):
                    continue

                increment = dsm_cost
                candidate = (
                    velocity_after,
                    arrival_velocity,
                    next_outgoing,
                    0.0,
                )

            if increment < selected_increment:
                selected_increment = increment
                selected = candidate

        if selected is None:
            return np.inf, None

        (
            velocity_after,
            arrival_velocity,
            next_outgoing,
            transition_cost,
        ) = selected

        total += float(np.linalg.norm(
            velocity_after - velocity_before
        ))

        if make_nodes:
            nodes.append({
                "type": "DSM",
                "time": float(dsm_epoch),
                "planet_id": "0",
                "r": dsm_r,
                "v_before": velocity_before,
                "v_after": velocity_after,
            })

        if leg < 4:
            total += float(transition_cost)
            if make_nodes:
                nodes.append({
                    "type": "GA",
                    "time": float(t1),
                    "planet_id": SEQUENCE[leg],
                    "r": states[leg + 1][0],
                    "v_before": arrival_velocity,
                    "v_after": next_outgoing,
                })
            outgoing = next_outgoing
        else:
            total += float(transition_cost)
            if make_nodes:
                nodes.append({
                    "type": "end",
                    "time": float(t1),
                    "planet_id": str(problem["end"].get("planet_id", "0")),
                    "r": states[-1][0],
                    "v_before": arrival_velocity,
                    "v_after": states[-1][1],
                })

    return float(total), nodes


def _verify_nodes(nodes):
    """Verify generated gravity assists with the evaluator-compatible primitive."""
    for node in nodes:
        if node["type"] != "GA":
            continue

        pid = str(node["planet_id"])
        minimum = _minimum_rp(pid)

        try:
            _, planet_velocity = _planet(pid, node["time"])
            periapsis, mismatch, feasible = tools.powered_flyby(
                np.asarray(node["v_before"], dtype=float),
                np.asarray(node["v_after"], dtype=float),
                planet_velocity,
                float(problem["planet_mu"][pid]),
                minimum,
            )

            if not bool(feasible):
                return False
            if not np.isfinite(float(periapsis)):
                return False
            if not np.isfinite(float(mismatch)):
                return False
            if float(periapsis) < minimum - 1.0e-3:
                return False
            if abs(float(mismatch)) > 1.0e-6:
                return False
        except Exception:
            return False

    return True


def _summary_seed(dates, dsms, altitudes, initial_vinf, angles):
    """Build a Cartesian chromosome from observed encounter and DSM epochs."""
    final_epoch = 0.5 * sum(_window(problem["end"]))
    dates = np.asarray(dates, dtype=float)
    boundaries = np.concatenate((dates, [final_epoch]))
    dsms = np.asarray(dsms, dtype=float)

    fractions = (
        (dsms - boundaries[:-1])
        / (boundaries[1:] - boundaries[:-1])
    )

    rp_factors = np.array([
        (
            float(problem["planet_radius"][pid])
            + float(altitudes[index])
        ) / float(problem["planet_radius"][pid])
        for index, pid in enumerate(SEQUENCE)
    ])

    return np.concatenate((
        dates,
        np.asarray(initial_vinf, dtype=float),
        fractions,
        rp_factors,
        np.asarray(angles, dtype=float),
    ))


